-- ─────────────── 座席マスタ（3拠点 × 2フロア × 3エリア × 10席 = 180席を自動生成） ───────────────
INSERT INTO seats (seat_id, base_name, area_name, f_name, seat_name)
SELECT
    ROW_NUMBER() OVER (ORDER BY b.base_name, f.f_name, a.area_name, n.num) AS seat_id,
    b.base_name,
    a.area_name,
    f.f_name,
    CONCAT(a.area_name, '-', LPAD(n.num, 2, '0')) AS seat_name
FROM (
    SELECT '三田' AS base_name UNION ALL
    SELECT '芝浦' UNION ALL
    SELECT '中野'
) b
CROSS JOIN (
    SELECT '1F' AS f_name UNION ALL SELECT '2F'
) f
CROSS JOIN (
    SELECT 'A' AS area_name UNION ALL SELECT 'B' UNION ALL SELECT 'C'
) a
CROSS JOIN (
    SELECT 1 AS num UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5
    UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9 UNION ALL SELECT 10
) n;

