-- 既存DB向け修正スクリプト（2026-06-08 その2）
--
-- 不具合：「在宅・出張で行先登録するとシステムエラー：予約の登録に失敗しました」
-- 原因  ：reservations.seat_id への外部キー制約 fk_reservations_seats が、
--         「座席なし」を表すために使っている seat_id = 0 を許容していない
--         （seats テーブルに seat_id = 0 の行は存在しないため、INSERT時に
--         外部キー制約違反になっていた）。
--
-- 対応  ：fk_reservations_seats を削除する。
--         アプリ側は常に「有効な座席ID」か「0（座席なし）」のどちらかをセットする
--         設計になっており、不正な値が入る心配はないため、外部キー制約自体を外す。
--
-- 適用方法：MySQLクライアントで
--   USE zaseki1;
--   SOURCE migration_2026-06-08_drop_seat_fk.sql;
-- のように実行する。
-- =========================================================

ALTER TABLE reservations
    DROP FOREIGN KEY fk_reservations_seats;
